    await setField('coupon', '3')
    await setField('price', '100')
    await calculate()
    await expect($('[data-finance-result="yieldRate"]')).toHaveText(expect.stringContaining('2.912621'))
    await chooseField('frequency', '3')
    expect(await $('[data-finance-field="issue"]').isExisting()).toBe(false)
    await setField('settlement', '2026-10-12')
    await setField('maturity', '2031-10-01')
    await chooseField('target', 'convexity')
    await setField('yieldRate', '-1')
